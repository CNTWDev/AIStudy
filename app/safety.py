"""学员写的话里有危险信号时，先关心人，不接着上课（docs/DESIGN.md §4.7.1）。

用在学员自由书写、AI 会接着回应的地方（思辨题）：
- 先用一份短词表看学员的话（不调用 AI，也不把这段话发出去）；
- AI 回应时也会判断，觉得学员可能有危险就返回 {"care": true}，不再讨论题目。
命中以后：停下这道题，给出求助渠道；这段话不存、不算一次学习，也不进思考画像。
这里只做「停下、指路」，不做诊断，也不做心理辅导。
"""
import re

CARE = {
    "title": "先停一下，这比题目重要",
    "text": "你写的话让我有点担心你。如果你正在经历很难熬的时刻，请找人说一说，不用一个人扛着。",
    "lines": [
        "全国心理援助热线 12356（24 小时）",
        "有生命危险请马上打 120 或 110",
        "也可以现在就告诉一个你信任的人：家人、朋友、医生",
    ],
}

# 第一人称、说的是自己的话才算：讨论「自杀率」「自残行为的研究」这类题目本身不算
_SIGNS = re.compile(
    r"(我|自己).{0,8}(想死|不想活|活不下去|活着没意思|活着没有意义|想自杀|要自杀|自杀算了|想自残|伤害自己|结束自己|了结自己|割腕|跳楼|轻生)"
    r"|不想活了|活不下去了|想死了|死了算了|结束生命算了"
    r"|\b(i want to die|kill myself|end my life|hurt myself|suicidal)\b",
    re.IGNORECASE,
)


def crisis(text: str) -> bool:
    """这段话里有没有自伤、轻生的信号（宁可多停一次，也不漏）。"""
    return bool(text) and bool(_SIGNS.search(text))
